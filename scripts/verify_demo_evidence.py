#!/usr/bin/env python3
"""Revalidate a real fresh demo and its explicitly authored browser record.

This executes no query and does not automate or invent a visual review. The
separate demo receipt, generated bytes and manual record must already exist.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'scripts'),str(ROOT / 'benchmarks')]
from evidence import source_identity, verify_receipt
from evidence_coverage import required_sources
from build import verify_build


def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(); parser.add_argument('--fresh-checkout',type=Path,required=True)
    parser.add_argument('--demo-dir',type=Path,required=True); parser.add_argument('--demo-receipt',type=Path,required=True)
    parser.add_argument('--browser-record',type=Path,required=True); args = parser.parse_args()
    fresh = args.fresh_checkout.resolve(); demo = args.demo_dir.resolve()
    if not demo.is_relative_to(fresh / '.local-runs'): raise ValueError('demo escaped the stated fresh checkout')
    commit = subprocess.check_output(['git','rev-parse','HEAD'],cwd=fresh,text=True).strip()
    if subprocess.check_output(['git','status','--porcelain'],cwd=fresh).strip(): raise ValueError('fresh source is dirty')
    identity = source_identity(fresh)
    marker = json.loads((fresh / '.local-runs/clean-scope.json').read_bytes())
    if (Path(marker['fresh_clone_root']).resolve() != fresh or marker['commit'] != commit
            or marker['source_sha256'] != identity['sha256']): raise ValueError('fresh checkout marker differs')
    receipt = json.loads(args.demo_receipt.read_bytes())
    if (not verify_receipt(args.demo_receipt) or receipt['verification_status'] != 'PASS' or receipt['exit_code'] != 0
            or receipt['git'] != {'commit':commit,'dirty':False}
            or receipt['source_before']['sha256'] != identity['sha256'] or receipt['source_after_sha256'] != identity['sha256']
            or receipt['command'][:2] != ['make','demo']): raise ValueError('no stable actual fresh make demo receipt')
    captured = dict(identity['files']); current = dict(source_identity(ROOT)['files'])
    # This current verifier is bound by its own command receipt. The recorded
    # fresh invocation must match every execution/renderer/contract dependency.
    execution_sources = required_sources('AC-008',ROOT) - {'scripts/verify_demo_evidence.py'}
    if any(captured.get(name) != current.get(name) for name in execution_sources):
        raise ValueError('current demo/product contract source differs from the recorded fresh demo')
    pointer = json.loads((fresh / 'target/debug/rillscope.build.json').read_bytes())
    build_receipt = (fresh / pointer['receipt']).resolve()
    if not build_receipt.is_relative_to(fresh / '.local-runs'): raise ValueError('fresh build receipt escaped')
    build = json.loads(build_receipt.read_bytes()); binary = fresh / build['bins']['rillscope']['path']
    verify_build(build_receipt,binary,name='rillscope',root=fresh,profile='dev')
    manifest = json.loads((demo / 'manifest.json').read_bytes())
    report = demo / 'report.html'; results = demo / 'results.json'
    if (manifest['implementation'] != 'rust' or manifest['cases'] != 3 or manifest['binary_sha256'] != sha(binary)
            or manifest['report_sha256'] != sha(report) or manifest['results_sha256'] != sha(results)
            or len(manifest['process_calls']) != 4): raise ValueError('generated demo identities differ')
    if any(sha(fresh / name) != digest for name,digest in manifest['inputs_sha256'].items()):
        raise ValueError('demo input changed')
    cases = {row['id']:row for row in json.loads(results.read_bytes())['cases']}
    if (set(cases) != {'allowed','denied','second'}
            or cases['allowed']['result']['rows'] != [[3,40]] or cases['allowed']['oracle_rows'] != [[3,40]]
            or cases['second']['result']['rows'] != [[1,999]] or cases['second']['oracle_rows'] != [[1,999]]
            or cases['denied']['result']['error']['code'] != 'E_FORBIDDEN' or 'rows' in cases['denied']['result']):
        raise ValueError('demo outcomes differ from the independently expected fixtures')
    record = json.loads(args.browser_record.read_bytes())
    if (record['review_kind'] != 'integrator-browser-visual-record' or record['inspection_only'] is not True
            or record['fresh_checkout_commit'] != commit or record['report_sha256'] != sha(report)
            or record['observed_allowed_rows'] != [[3,40]] or record['observed_second_tenant_rows'] != [[1,999]]
            or record['observed_denial'] != 'E_FORBIDDEN; no result rows' or record['visual_findings'] != []
            or len(record['keyboard_checks']) < 3 or len(record['screenshots']) < 2):
        raise ValueError('no matching explicit browser/manual record')
    screenshots = []
    for name in record['screenshots']:
        path = args.browser_record.parent / name
        if Path(name).name != name or not path.is_file(): raise ValueError('missing/nonlocal screenshot record')
        screenshots.append(sha(path))
    result = {'status':'PASS','campaign':'fresh-committed-Rust-demo', 'fresh_checkout_commit':commit,
              'fresh_checkout':True,'recorded_make_demo_status':'PASS','current_execution_source_identity_matches':True,
              'implementation':'rust','cases':3,'report_sha256':sha(report),'results_sha256':sha(results),
              'binary_sha256':sha(binary),'browser_review_status':'RECORDED','browser_record_sha256':sha(args.browser_record),
              'actual_screenshot_sha256':screenshots,'oracle_match':True,
              'scope':'revalidated actual fresh demo plus integrator browser record; no new query execution, user study or independent visual audit'}
    print(json.dumps(result,indent=2)); return 0


if __name__ == '__main__': raise SystemExit(main())
